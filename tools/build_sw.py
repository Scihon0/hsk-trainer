"""Write sw.js with a precache list of every app file, versioned by content hash.
Run from the app folder: python3 -I tools/build_sw.py
"""
import hashlib, json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = ["./", "index.html", "app.js", "manifest.webmanifest"]
for d in ["content", "audio", "pics", "icons"]:
    files += sorted(str(p.relative_to(root)) for p in (root / d).rglob("*") if p.is_file() and not p.name.startswith("."))
h = hashlib.sha256(Path(__file__).read_bytes())
for f in files[1:]:
    h.update(f.encode()); h.update((root / f).read_bytes())
version = h.hexdigest()[:10]

sw = f"""/* Generated by tools/build_sw.py. Precaches every file so the app works with no network. */
const CACHE = "hsk-{version}";
const FILES = {json.dumps(files, ensure_ascii=False)};
self.addEventListener("install", e => {{
  e.waitUntil((async () => {{
    const c = await caches.open(CACHE);
    // add in small batches so one slow file doesn't fail the whole install
    for (let i = 0; i < FILES.length; i += 20) await c.addAll(FILES.slice(i, i + 20).map(u => new Request(u, {{ cache: "reload" }})));
    await self.skipWaiting();
  }})());
}});
self.addEventListener("activate", e => {{
  e.waitUntil((async () => {{
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
    const n = (await (await caches.open(CACHE)).keys()).length;
    for (const cl of await self.clients.matchAll()) cl.postMessage({{ type: "cached", count: n }});
  }})());
}});
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  // App code (page, scripts, small data): network first so updates show up immediately; cache when offline.
  const p = url.pathname;
  const fresh = req.mode === "navigate" || /[.](html|js|webmanifest)$/.test(p) || /content[/](?!dict)[^/]+[.]json$/.test(p);
  e.respondWith((async () => {{
    const c = await caches.open(CACHE);
    if (fresh) {{
      try {{
        const r = await fetch(req, {{ cache: "no-cache" }});
        if (r.ok) {{ c.put(req.mode === "navigate" ? "index.html" : req, r.clone()); return r; }}
      }} catch (err) {{ }}
      return (await c.match(req.mode === "navigate" ? "index.html" : req, {{ ignoreSearch: true }})) || (await c.match("index.html")) || Response.error();
    }}
    // Audio, pictures, dictionary: cache first (big, rarely change).
    const hit = await c.match(req, {{ ignoreSearch: true }});
    if (hit) return hit;
    try {{ return await fetch(req); }} catch (err) {{ return Response.error(); }}
  }})());
}});
"""
(root / "sw.js").write_text(sw, "utf-8")
size = sum((root / f).stat().st_size for f in files[1:])
print(f"sw.js: {len(files)} files, {size/1048576:.1f} MB, cache hsk-{version}")
